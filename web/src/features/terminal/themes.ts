export const CUSTOM_PREFIX = 'custom:'

const byId = new Map(BUILTIN_SCHEMES.map((s) => [s.id, s]))
/** Former ids of renamed built-in schemes, so saved settings keep resolving. */
const ALIASES: Record<string, string> = { mobaxterm: 'classic' }

/** All selectable schemes: built-ins followed by the user's custom schemes (ids prefixed with `custom:`). */
export function listSchemes(custom: readonly TerminalScheme[] = []): TerminalScheme[] {
  return [...BUILTIN_SCHEMES, ...custom.map((c) => ({ ...c, id: c.id.startsWith(CUSTOM_PREFIX) ? c.id : CUSTOM_PREFIX + c.id }))]
}

/** Look a scheme up by id (built-in or custom); falls back to Termstead Dark/Light. */
export function findScheme(id: string | undefined, custom: readonly TerminalScheme[] = [], fallbackDark = true): TerminalScheme {
  if (id) {
    const b = byId.get(ALIASES[id] ?? id)
    if (b) return b
    if (id.startsWith(CUSTOM_PREFIX)) {
      const raw = id.slice(CUSTOM_PREFIX.length)
      const c = custom.find((s) => s.id === raw || s.id === id)
      if (c) return normalizeScheme(c)
    }
  }
  return byId.get(fallbackDark ? 'termstead-dark' : 'termstead-light')!
}

/** Scheme for the current UI theme (TERM-9 auto light/dark switching). */
export function resolveScheme(s: Pick<TerminalSettings, 'theme' | 'lightTheme' | 'matchAppTheme' | 'customSchemes'>, uiDark: boolean): TerminalScheme {
  const id = s.matchAppTheme && !uiDark && s.lightTheme ? s.lightTheme : s.theme
  return findScheme(id, s.customSchemes, uiDark)
}

