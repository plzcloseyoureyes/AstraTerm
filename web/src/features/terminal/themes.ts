const HEX6 = /^#[0-9a-f]{6}$/i
const HEX3 = /^#[0-9a-f]{3}$/i
const HEX8 = /^#[0-9a-f]{8}$/i

/** Normalise a colour string to #rrggbb (accepts #rgb, #rrggbbaa, rgb()/rgba()); returns undefined when unparsable. */
export function toHex(color: string | undefined | null): string | undefined {
  if (!color || typeof color !== 'string') return undefined
  const c = color.trim()
  if (HEX6.test(c)) return c.toLowerCase()
  if (HEX3.test(c)) return ('#' + c.slice(1).replace(/./g, (x) => x + x)).toLowerCase()
  if (HEX8.test(c)) return c.slice(0, 7).toLowerCase()
  const m = c.match(/^rgba?\(\s*(\d{1,3})[\s,]+(\d{1,3})[\s,]+(\d{1,3})/i)
  if (m) return rgbToHex(+m[1], +m[2], +m[3])
  return undefined
}

export function rgbToHex(r: number, g: number, b: number): string {
  const h = (v: number) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')
  return `#${h(r)}${h(g)}${h(b)}`
}

export function hexToRgb(hex: string): [number, number, number] {
  const h = toHex(hex) ?? '#000000'
  const n = parseInt(h.slice(1), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

/** Relative luminance (WCAG). */
export function luminance(hex: string): number {
  const [r, g, b] = hexToRgb(hex).map((v) => {
    const c = v / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

export function isDarkScheme(s: Pick<TerminalScheme, 'background'>): boolean {
  return luminance(s.background) < 0.4
}

/** Mix two colours (t = 0 → a, 1 → b). */
export function mix(a: string, b: string, t: number): string {
  const [ar, ag, ab] = hexToRgb(a)
  const [br, bg, bb] = hexToRgb(b)
  return rgbToHex(ar + (br - ar) * t, ag + (bg - ag) * t, ab + (bb - ab) * t)
}

function withAlpha(hex: string, alpha: number): string {
  const [r, g, b] = hexToRgb(hex)
  return `rgba(${r}, ${g}, ${b}, ${Math.max(0, Math.min(1, alpha))})`
}

/** Fill in missing optional colours and normalise every value to #rrggbb. */
export function normalizeScheme(s: TerminalScheme): TerminalScheme {
  const bg = toHex(s.background) ?? '#000000'
  const fg = toHex(s.foreground) ?? '#ffffff'
  const out: TerminalScheme = {
    id: s.id,
    name: s.name || 'Untitled',
    background: bg,
    foreground: fg,
    cursor: toHex(s.cursor) ?? fg,
    cursorAccent: toHex(s.cursorAccent) ?? bg,
    selectionBackground: toHex(s.selectionBackground) ?? mix(bg, fg, 0.28),
    selectionForeground: toHex(s.selectionForeground),
  } as TerminalScheme
  const fallback = BUILTIN_SCHEMES[isDarkScheme({ background: bg }) ? 0 : 1]
  for (const k of ANSI_KEYS) out[k] = toHex(s[k]) ?? fallback[k]
  return out
}

/** xterm ITheme for a scheme; `opacity` < 1 makes the background translucent (requires allowTransparency). */
export function toXtermTheme(s: TerminalScheme, opacity = 1): ITheme {
  const n = normalizeScheme(s)
  const dark = isDarkScheme(n)
  const theme: ITheme = {
    background: opacity < 1 ? withAlpha(n.background, opacity) : n.background,
    foreground: n.foreground,
    cursor: n.cursor,
    cursorAccent: n.cursorAccent,
    selectionBackground: n.selectionBackground,
    selectionForeground: n.selectionForeground,
    selectionInactiveBackground: withAlpha(n.selectionBackground ?? mix(n.background, n.foreground, 0.28), 0.6),
    scrollbarSliderBackground: withAlpha(n.foreground, dark ? 0.18 : 0.22),
    scrollbarSliderHoverBackground: withAlpha(n.foreground, dark ? 0.32 : 0.36),
    scrollbarSliderActiveBackground: withAlpha(n.foreground, 0.45),
    overviewRulerBorder: n.background,
  }
  for (const k of ANSI_KEYS) theme[k] = n[k]
  return theme
}

/** Colours of search decorations derived from the scheme (xterm requires #rrggbb). */
export function searchColors(s: TerminalScheme) {
  const n = normalizeScheme(s)
  const dark = isDarkScheme(n)
  return {
    matchBackground: dark ? mix(n.background, '#d4a017', 0.35) : mix(n.background, '#f5c542', 0.55),
    matchBorder: dark ? '#8a7a2a' : '#c9a227',
    matchOverviewRuler: '#d4a017',
    activeMatchBackground: dark ? '#b8860b' : '#f59e0b',
    activeMatchBorder: dark ? '#ffd166' : '#b45309',
    activeMatchColorOverviewRuler: '#ff9f1c',
  }
}

/** Generate a unique id for a new custom scheme. */
export function newSchemeId(): string {
  const b = new Uint8Array(6)
  crypto.getRandomValues(b)
  return Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('')
}
